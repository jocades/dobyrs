use crate::board::{Board, Color::*, Piece, Role};

pub fn evaluate(board: &Board) -> i32 {
    let mut score = 0;

    for (color, role) in Piece::ALL {
        for sq in board.bitboards[color][role] {
            let sq = color.fold(sq, sq.mirror());
            let value = ROLE_VALUE[role as usize] + PSQT[role as usize][sq as usize];
            score += color.fold(value, -value);
        }
    }

    board.side.fold(score, -score)
}

const ROLE_VALUE: [i32; 6] = [100, 320, 330, 500, 900, 0];

